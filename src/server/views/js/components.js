/**
 * Reusable Status Badge
 */
export function Badge({ text, variant = 'default' }) {
  const cls = variant === '3sks' ? 'badge-3sks' : variant === '2sks' ? 'badge-2sks' : variant === 'completed' ? 'badge-completed' : variant === 'elearning' ? 'badge-elearning' : 'badge';
  return `<span class="badge ${cls}">${text}</span>`;
}

