/**
 * Reusable Action Button
 */
export function Button({ id = '', text = '', icon = '', variant = 'btn', disabled = false, onclick = '', type = 'button', style = '' }) {
  const cls = variant === 'primary' ? 'btn' : variant === 'secondary' ? 'btn btn-secondary' : variant === 'danger' ? 'btn btn-ghost-danger' : variant;
  return `
    <button id="${id}" type="${type}" class="${cls}" ${disabled ? 'disabled' : ''} ${onclick ? `onclick="${onclick}"` : ''} style="${style}">
      ${icon || ''}
      ${text ? `<span>${text}</span>` : ''}
    </button>
  `;
}

/**
 * Reusable Action Chip (Edit & Delete in mobile/desktop cards)
 */
export function ActionChip({ type = 'edit', text = '', onclick = '' }) {
  if (type === 'broadcast') {
    return `
      <button class="action-chip-edit" style="color: #60a5fa; border-color: rgba(59, 130, 246, 0.25); background: rgba(59, 130, 246, 0.08);" onclick="${onclick}">
        <svg viewBox="0 0 24 24" style="width: 12px; height: 12px; stroke: currentColor; fill: none; stroke-width: 2;"><line x1="22" y1="2" x2="11" y2="13"/><polygon points="22 2 15 22 11 13 2 9 22 2"/></svg>
        <span>${text || 'Broadcast'}</span>
      </button>
    `;
  }
  if (type === 'edit') {
    return `
      <button class="action-chip-edit" onclick="${onclick}">
        ${Icons.edit}
        <span>${text || 'Ubah'}</span>
      </button>
    `;
  }
  return `
    <button class="action-chip-danger" onclick="${onclick}">
      ${Icons.trash}
      <span>${text || 'Hapus'}</span>
    </button>
  `;
}

/**
 * Reusable Toggle Switch
 */
